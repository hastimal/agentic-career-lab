    def get_resources_for_skill(self, skill: str) -> list[LearningResource]:
        """Return verified learning resources for a skill, or a cleanly labeled discovery guide."""
        normalized = skill.strip()
        # Direct match or case-insensitive match
        for key in self.catalog:
            if key.lower() == normalized.lower():
                return self.catalog[key]

        # Cleanly labeled discovery fallback (does NOT invent courses or fake URLs)
        return [
            LearningResource(
                resource_id=f"disc-{normalized.lower().replace(' ', '-')}-doc",
                title=f"Official Documentation & Community Tutorials: {normalized}",
                provider="Verified Documentation Portal",
                resource_type="Documentation",
                category="LEARN",
                url=None,
                skill=normalized,
                relevant_skills=[normalized],
                reason=f"Review official documentation and reputable community guides for {normalized}.",
                difficulty="Intermediate",
                estimated_duration="3-5 hours",
                prerequisites=["Core Programming Concepts"],
                learning_outcome=f"Understand architecture, key API patterns, and testing for {normalized}.",
                practical_exercise=f"Build a standalone working prototype demonstrating {normalized}.",
                free_or_paid="Free",
                is_verified=False,
            )
        ]

    def get_resource_by_id(self, resource_id: str) -> LearningResource | None:
        """Find resource by canonical ID."""
        for res_list in self.catalog.values():
            for res in res_list:
                if res.resource_id == resource_id:
                    return res
        return None

    def get_resources_by_category(self, skills: list[str], category: str) -> list[LearningResource]:
        """Get deduplicated resources for target skills filtered by category (WATCH, LEARN, PRACTICE, BUILD)."""
        seen_ids = set()
        results: list[LearningResource] = []
        for s in skills:
            for r in self.get_resources_for_skill(s):
                if r.category.upper() == category.upper() and r.resource_id not in seen_ids:
                    seen_ids.add(r.resource_id)
                    results.append(r)
        return results

    def get_all_skills(self) -> list[str]:
        """Return list of all curated skills in the catalog."""
        return list(self.catalog.keys())

    def get_full_catalog(self) -> list[LearningResource]:
        """Return flat list of all curated resources."""
        resources: list[LearningResource] = []
        for res_list in self.catalog.values():
            resources.extend(res_list)
        return resources
